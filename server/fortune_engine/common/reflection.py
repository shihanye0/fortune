# -*- coding: utf-8 -*-
"""今日一问：确定性题池，按用户+日期稳定取题（Co-Star 式自省问题）。"""

REFLECTION_QUESTIONS = (
    "今天什么事值得你全力以赴？",
    "如果今天只能完成一件事，你会选哪件？",
    "你在逃避的那件事，最坏结果是什么？",
    "最近一次改变主意，是因为什么？",
    "今天可以为未来的自己积累什么？",
    "上一次果断说“不”，是什么时候？",
    "什么事让你最近充满能量？",
    "如果运气是准备遇上了机会，你准备了什么？",
    "今天想对谁表达感谢？",
    "拖延最久的那件事，究竟卡在哪里？",
    "最近有什么信号，你可能正在忽视？",
    "你的耐心今天留给谁了？",
    "什么成果是你希望被人看见的？",
    "今天愿意为什么承担一点风险？",
    "身体最近在提醒你什么？",
    "五年后的你，会感谢今天的哪个决定？",
)


def pick_reflection(user_key: int, day_seed: int) -> str:
    """按用户与日期取一题：同用户同日稳定，不同用户错开。"""
    return REFLECTION_QUESTIONS[(user_key * 31 + day_seed) % len(REFLECTION_QUESTIONS)]
